import {render,screen,within} from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import {expect,it} from 'vitest';
import raw from './goal-graph-actual-integrity-task-fixture.json?raw';
import {GoalGraphExecutionHistory} from './GoalGraphExecutionHistory';
import {graphDetailsShape,graphDetailsMeetFloor,graphTaskAcceptanceMatchesTask,graphViewConsistent} from './goal-graph-guards';
import type {GraphRunDetails} from './goal-graph-types';
import type {GoalScope} from './goal-api';
import type {Task} from './api';
const actual=()=>JSON.parse(raw) as {task:Task;scope:GoalScope;graph_details:GraphRunDetails};
it('binds the actual accepted Task projection to the Integrity graph without treating the check as semantic acceptance',()=>{
  const {task,scope,graph_details:view}=actual();
  expect(graphDetailsShape(view,task,scope)).toBe(true);
  expect(graphViewConsistent(view)).toBe(true);
  expect(graphTaskAcceptanceMatchesTask(view.task_acceptance,task,scope,view)).toBe(true);
  expect(view.validations[0].task_acceptance).toBe('not_established');
  expect(view.validations[0].correctness).toBe('not_established');
  expect(graphTaskAcceptanceMatchesTask(view.task_acceptance,{...task,acceptance_sequence:task.acceptance_sequence!+1},scope,view)).toBe(false);
});
it('displays the complete original observation as folded readonly JSON with its actual goal_io and no action',async()=>{
  const user=userEvent.setup(),{task,scope,graph_details:view}=actual();
  render(<GoalGraphExecutionHistory view={view} task={task} scope={scope} language="en"/>);
  const toggle=screen.getByText('Result checks · 1',{selector:'summary'});
  const section=toggle.parentElement!;
  expect(section).not.toHaveAttribute('open');
  await user.click(toggle);
  const pre=section.querySelector('pre')!;
  expect(pre).not.toBeNull();
  const details=pre.parentElement!;
  expect(details).not.toHaveAttribute('open');
  await user.click(within(details).getByText('Details',{selector:'summary'}));
  expect(pre).toBeVisible();
  const displayed=JSON.parse(pre.textContent!);
  expect(displayed).toEqual(view.validations[0]);
  expect(displayed.observation).toEqual(view.validations[0].observation);
  expect(displayed.observation.goal_io.state).toBe('observed');
  expect(displayed.observation.goal_io.artifact_stability).toBe('before_after_fd_pin_and_sha256');
  expect(displayed.correctness).toBe('not_established');
  expect(screen.getAllByText('File integrity, declared schemas and successful commands do not establish semantic acceptance.').length).toBeGreaterThan(0);
  expect(screen.queryByRole('button')).toBeNull();
  expect(screen.queryByRole('link')).toBeNull();
});
it('retains the complete original observation under the existing evidence floor',()=>{
  const {graph_details:before}=actual(),changed=structuredClone(before);
  (changed.validations[0].observation as Record<string,any>).goal_io.artifact_bytes++;
  changed.ledger_revision++;
  changed.run={...changed.run,revision:changed.run.revision+1};
  expect(graphDetailsMeetFloor(changed,{summary:before,details:before})).toBe(false);
});
